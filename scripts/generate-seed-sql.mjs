#!/usr/bin/env node
// Writes supabase/seed.sql: INSERT ... ON CONFLICT statements for the demo restaurants,
// categories and items (no users: create accounts in the dashboard or with seed-supabase.mjs).
//
//   node scripts/generate-seed-sql.mjs
//
// Then paste supabase/seed.sql into the Supabase SQL editor, after running supabase/migrations
// 0001, 0002 and 0003 in order (the restaurant rows need the timezone column from 0002).

import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ROOT, categoryRow, cleanEntry, itemRows, loadSeed, restaurantRow } from "./lib/seed-files.mjs";

const OUT = path.join(ROOT, "supabase", "seed.sql");

const JSON_COLUMNS = new Set(["theme", "contact", "opening_hours", "options"]);
const ARRAY_COLUMNS = new Set(["tags"]);
const TIMESTAMP_COLUMNS = new Set(["created_at", "updated_at"]);

const quote = (s) => `'${String(s).replace(/'/g, "''")}'`;

function literal(column, value) {
  if (value === null || value === undefined) return "null";
  if (JSON_COLUMNS.has(column)) return `${quote(JSON.stringify(value))}::jsonb`;
  if (ARRAY_COLUMNS.has(column)) {
    return value.length ? `array[${value.map(quote).join(", ")}]::text[]` : `'{}'::text[]`;
  }
  if (TIMESTAMP_COLUMNS.has(column)) return `${quote(value)}::timestamptz`;
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "null";
  return quote(value);
}

function upsert(table, rows, conflict = "id") {
  if (rows.length === 0) return "";
  const columns = [...new Set(rows.flatMap((r) => Object.keys(r)))];
  const values = rows
    .map((r) => `  (${columns.map((c) => (c in r ? literal(c, r[c]) : "default")).join(", ")})`)
    .join(",\n");
  const updates = columns
    .filter((c) => c !== conflict && c !== "created_at")
    .map((c) => `  ${c} = excluded.${c}`)
    .join(",\n");
  return `insert into public.${table} (${columns.join(", ")}) values\n${values}\non conflict (${conflict}) do update set\n${updates};\n`;
}

const seed = loadSeed();
const parts = [
  "-- Demo content generated by scripts/generate-seed-sql.mjs. Do not edit by hand:",
  "-- change lib/data/seed/restaurants/*.json and re-run the script.",
  "-- Run AFTER supabase/migrations 0001, 0002 and 0003 (in order). Safe to run again (upserts).",
  "",
  "begin;",
  "",
];
const totals = { restaurants: 0, categories: 0, items: 0 };

for (const entry of seed.restaurants) {
  const r = entry.restaurant;
  const cleaned = cleanEntry(entry);
  if (cleaned.fatal) {
    console.log(`  SKIP  ${entry.file}: ${cleaned.fatal}`);
    continue;
  }
  cleaned.warnings.forEach((w) => console.log(`  WARN  ${entry.file}: ${w}`));
  const categories = cleaned.categories.map((c, idx) => categoryRow(c, r.id, idx));
  const items = itemRows(cleaned.items, r.id);
  parts.push(`-- ${r.slug} ------------------------------------------------------------`);
  parts.push(upsert("restaurants", [restaurantRow(r)]));
  parts.push(upsert("categories", categories));
  parts.push(upsert("items", items));
  totals.restaurants++;
  totals.categories += categories.length;
  totals.items += items.length;
  console.log(`  OK    ${r.slug}: ${categories.length} categories, ${items.length} items`);
}

parts.push("commit;", "");
mkdirSync(path.dirname(OUT), { recursive: true });
writeFileSync(OUT, parts.filter((p) => p !== "").join("\n") + "\n", "utf8");
console.log(
  `\nWrote ${path.relative(ROOT, OUT)}: ${totals.restaurants} restaurants, ${totals.categories} categories, ${totals.items} items.`,
);
if (totals.restaurants === 0) console.log("No restaurant files found in lib/data/seed/restaurants/*.json.");
